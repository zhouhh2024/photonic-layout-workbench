from __future__ import annotations

from collections import defaultdict
from typing import Iterable, Mapping

from .models import ClusterSpec, SpecError, TerminalSpec


def terminal_key(terminal: TerminalSpec) -> tuple[str, str]:
    return terminal.instance_id, terminal.port_name


def assign_terminal_nets(
    spec: ClusterSpec,
    instance_ports: Mapping[str, Iterable[str]],
) -> tuple[dict[tuple[str, str], str], dict[str, str]]:
    """Assign every physical device terminal to one and only one logical net."""
    assigned: dict[tuple[str, str], str] = {}
    external_to_net: dict[str, str] = {}

    for net in spec.nets:
        for terminal in net.terminals:
            key = terminal_key(terminal)
            if key in assigned:
                raise SpecError(
                    f"terminal {key[0]}.{key[1]} is reused by nets "
                    f"{assigned[key]!r} and {net.net_id!r}"
                )
            assigned[key] = net.net_id

    for external in spec.external_ports:
        key = terminal_key(external.terminal)
        if key in assigned:
            raise SpecError(
                f"external port {external.name!r} reuses connected terminal "
                f"{key[0]}.{key[1]}"
            )
        assigned[key] = external.name
        external_to_net[external.name] = external.name

    known_terminals = {
        (instance_id, port_name)
        for instance_id, port_names in instance_ports.items()
        for port_name in port_names
    }
    unknown = sorted(set(assigned) - known_terminals)
    if unknown:
        rendered = ", ".join(f"{instance}.{port}" for instance, port in unknown)
        raise SpecError(f"spec references ports not present on their devices: {rendered}")

    missing = sorted(known_terminals - set(assigned))
    if missing:
        rendered = ", ".join(f"{instance}.{port}" for instance, port in missing)
        raise SpecError(
            "every device port must belong to an internal net or an external port; "
            f"unassigned: {rendered}"
        )
    return assigned, external_to_net


def validate_device_graph(spec: ClusterSpec) -> dict[str, object]:
    adjacency: dict[str, set[str]] = defaultdict(set)
    for instance in spec.instances:
        adjacency[instance.instance_id]
    for net in spec.nets:
        left, right = net.terminals
        adjacency[left.instance_id].add(right.instance_id)
        adjacency[right.instance_id].add(left.instance_id)

    components: list[list[str]] = []
    remaining = set(adjacency)
    while remaining:
        start = sorted(remaining)[0]
        visited: set[str] = set()
        pending = [start]
        while pending:
            current = pending.pop()
            if current in visited:
                continue
            visited.add(current)
            pending.extend(adjacency[current] - visited)
        components.append(sorted(visited))
        remaining -= visited
    components.sort(key=lambda value: (-len(value), value))
    primary = set(components[0])
    disconnected = sorted(set(adjacency) - primary)
    if spec.require_connected_device_graph and disconnected:
        raise SpecError(
            "device graph is disconnected; unreachable instances: " + ", ".join(disconnected)
        )
    return {
        "connected": len(components) == 1,
        "component_count": len(components),
        "components": components,
        "visited_instances": sorted(primary),
        "disconnected_instances": disconnected,
    }


def render_reference_netlist(
    spec: ClusterSpec,
    instance_ports: Mapping[str, Iterable[str]],
    instance_families: Mapping[str, str],
) -> str:
    assigned, _ = assign_terminal_nets(spec, instance_ports)
    external_order = [port.name for port in spec.external_ports]
    lines = [
        "* Generated by photonic-cluster-generator from the same specification as the GDS",
        f".subckt {spec.cluster_name} {' '.join(external_order)}".rstrip(),
    ]
    instance_by_id = {instance.instance_id: instance for instance in spec.instances}
    for instance_id, port_names in instance_ports.items():
        instance = instance_by_id[instance_id]
        nets = [assigned[(instance_id, port_name)] for port_name in port_names]
        parameter_tokens = [
            f"{key}={_netlist_value(value)}"
            for key, value in sorted(instance.parameters.items())
        ]
        suffix = " " + " ".join(parameter_tokens) if parameter_tokens else ""
        lines.append(
            f"X{instance_id} {' '.join(nets)} {instance_families[instance_id]}{suffix}"
        )
    lines.extend([f".ends {spec.cluster_name}", ""])
    return "\n".join(lines)


def _netlist_value(value: object) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value).replace(" ", "_")
